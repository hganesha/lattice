export function useEvaluationMessages() {
  const intl = useIntl()
  return {
    t: (key: EvaluationMessageKey, values?: Record<string, PrimitiveType>) => intl.formatMessage(evaluationMessages[key], values),
    formatDate: intl.formatDate,
    formatNumber: intl.formatNumber,
  }
}

